import { expect, test } from "@playwright/test";

let browserErrors: string[];

test.beforeEach(async ({ page }) => {
  browserErrors = [];
  // Start collecting before navigation to include failures during app startup.
  page.on("pageerror", (error) => browserErrors.push(error.message));
  await page.goto("/");

  await expect(page.locator(".plane-marker")).toHaveCount(3);
});

test.afterEach(() => {
  expect(browserErrors).toEqual([]);
});

test("opens live details and a trail, then releases both on close", async ({
  page,
}) => {
  const marker = page.locator(".plane-marker").first();
  // Aircraft IDs are generated by the real backend; read the rendered marker.
  const id = (await marker.getAttribute("title"))!;
  await marker.click({ force: true });
  const dialog = page.getByRole("dialog", { name: "Aircraft details" });

  await expect(dialog).toBeVisible();
  await expect(
    dialog
      .locator("dt")
      .filter({ hasText: /^id$/ })
      .locator("..")
      .locator("dd"),
  ).toHaveText(id);
  await expect(page.locator(".leaflet-overlay-pane path")).toHaveCount(1);
  // More than one sample must arrive to produce a visible line segment.
  await expect(page.locator(".leaflet-overlay-pane path")).toHaveAttribute(
    "d",
    /L/,
  );

  await page.getByRole("button", { name: "Close aircraft details" }).click();

  await expect(dialog).toHaveCount(0);
  // Leaflet retains the cleared layer for reuse and renders an empty path.
  await expect(page.locator(".leaflet-overlay-pane path")).toHaveAttribute(
    "d",
    "M0 0",
  );
});

test("switches aircraft without keeping the previous details", async ({
  page,
}) => {
  const markers = page.locator(".plane-marker");
  await markers.nth(0).click({ force: true });
  const dialog = page.getByRole("dialog");

  await expect(dialog.locator("dt").filter({ hasText: /^id$/ })).toBeVisible();
  await page.keyboard.press("Escape");

  await expect(dialog).toHaveCount(0);

  const id = (await markers.nth(1).getAttribute("title"))!;
  await markers.nth(1).click({ force: true });

  await expect(
    dialog
      .locator("dt")
      .filter({ hasText: /^id$/ })
      .locator("..")
      .locator("dd"),
  ).toHaveText(id);
});

test("continues moving existing markers as real server positions arrive", async ({
  page,
}) => {
  const marker = page.locator(".plane-marker").first();
  // Zoom in so real movement is visible despite Leaflet pixel rounding.
  for (let zoom = 0; zoom < 5; zoom++)
    await page.getByRole("button", { name: "Zoom in" }).click();

  const original = await marker.getAttribute("style");
  await expect.poll(() => marker.getAttribute("style")).not.toBe(original);

  await expect(page.locator(".plane-marker")).toHaveCount(3);
});
